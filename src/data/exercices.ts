/** Crée une entrée du catalogue ; la zone est vérifiée par rapport au muscle principal. */
function ex<M extends MuscleId>(
  id: string,
  nom: string,
  type: TypeExercice,
  musclePrincipal: M,
  zone: ZoneDe<M>,
  articulation: Articulation,
  sens: Sens,
  positionCharge: PositionCharge,
  musclesSecondaires: MuscleId[],
  consignes: string[],
): ExerciceCatalogue {
  return {
    id,
    nom,
    type,
    musclePrincipal,
    musclesSecondaires,
    mouvement: { articulation, sens },
    zone,
    positionCharge,
    consignes,
    reference: REFERENCES.has(id),
  };
}

