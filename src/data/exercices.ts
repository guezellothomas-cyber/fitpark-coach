/**
 * Catalogue des exercices, classés par type de matériel (pas par marque).
 * Les identifiants (id) ne doivent jamais changer : l'historique y fait référence.
 *
 * Chaque ligne ex(...) se lit ainsi :
 *   ex(id, nom, type, muscle principal, zone,
 *      articulation, sens, position de charge,
 *      [muscles secondaires],
 *      [consignes])
 */
